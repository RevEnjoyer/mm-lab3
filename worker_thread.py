"""
Поток для асинхронной загрузки файла.

Лабораторная работа 2.2, вариант 1: асинхронная загрузка файла.
Читает файл небольшими порциями (чанками) в фоновом потоке, сообщая
прогресс и результат основному потоку через сигналы.
"""

import os
import time

from PyQt6.QtCore import QThread, pyqtSignal

# Размер одной порции чтения в байтах. Чем он меньше, тем чаще
# отправляется сигнал progress (плавнее прогресс-бар), но тем больше
# накладных расходов на сами сигналы. 64 КБ - разумный компромисс.
CHUNK_SIZE = 65536

# Искусственная задержка между чтением чанков (секунды). Реальное чтение
# с диска для небольших тестовых файлов происходит почти мгновенно,
# и прогресс-бар просто "мигнёт" от 0 до 100 за долю секунды - задержка
# нужна исключительно для того, чтобы увидеть процесс глазами при
# демонстрации. Для реальной сетевой загрузки эта строка не нужна -
# задержку создаст сама сеть.
SIMULATED_DELAY = 0.03


class WorkerThread(QThread):
    """Фоновый поток, читающий файл порциями и сообщающий о прогрессе."""

    # pyqtSignal(int) - сигнал прогресса, значение от 0 до 100.
    progress = pyqtSignal(int)

    # Сигнал успешного завершения: имя файла и его размер в байтах.
    # Два параметра в одном сигнале - сигналы Qt могут нести несколько
    # значений одновременно, как обычная функция с несколькими аргументами.
    result_ready = pyqtSignal(str, int)

    # Отдельный сигнал для ошибок - намеренно НЕ пытаемся втиснуть
    # сообщение об ошибке в result_ready, чтобы обработчики успеха
    # и ошибки в основном потоке были полностью независимы друг от друга.
    error_occurred = pyqtSignal(str)

    def __init__(self, file_path, parent=None):
        super().__init__(parent)
        # Параметры задачи передаются через конструктор ДО запуска
        # потока (.start()), а не через глобальные переменные - так
        # можно безопасно создавать несколько независимых загрузок.
        self.file_path = file_path

    def run(self):
        """
        Выполняется в фоновом потоке при вызове self.start().

        ВАЖНО: внутри run() нельзя напрямую трогать виджеты GUI -
        только эмитить сигналы, которые Qt сам доставит в основной
        поток и там же вызовет подключённые к ним обработчики.
        """
        try:
            # Проверяем существование файла уже внутри потока (а не до
            # его запуска) - это намеренно: само чтение файла тоже может
            # быть долгим, и вся файловая работа должна идти в фоне,
            # не блокируя GUI даже на этапе проверок.
            if not os.path.isfile(self.file_path):
                self.error_occurred.emit(f'Файл не найден: {self.file_path}')
                return

            total_size = os.path.getsize(self.file_path)

            # Пустой файл - особый случай: деление на total_size ниже
            # привело бы к ZeroDivisionError. Считаем загрузку пустого
            # файла мгновенно успешной.
            if total_size == 0:
                self.progress.emit(100)
                self.result_ready.emit(os.path.basename(self.file_path), 0)
                return

            bytes_read = 0
            # 'rb' - открываем в БИНАРНОМ режиме: файл может быть любым
            # (не только текстовым), читать его как текст было бы ошибкой.
            with open(self.file_path, 'rb') as file:
                while True:
                    chunk = file.read(CHUNK_SIZE)
                    # Пустой chunk означает, что файл прочитан до конца.
                    if not chunk:
                        break

                    bytes_read += len(chunk)
                    # Целочисленный процент от 0 до 100.
                    percent = int(bytes_read / total_size * 100)
                    self.progress.emit(percent)

                    time.sleep(SIMULATED_DELAY)

            # Отправляем 100% явно - при больших total_size последний
            # процент из-за округления вниз (int(...)) иногда не достигает
            # ровно 100, и прогресс-бар визуально "не доходит до конца".
            self.progress.emit(100)
            self.result_ready.emit(os.path.basename(self.file_path), total_size)

        except PermissionError as error:
            # Нет прав на чтение файла (например, системный файл).
            self.error_occurred.emit(f'Нет доступа к файлу: {error}')
        except OSError as error:
            # Более общая файловая ошибка (диск отключили на лету,
            # файл удалили прямо во время чтения и т.п.).
            self.error_occurred.emit(f'Ошибка чтения файла: {error}')
